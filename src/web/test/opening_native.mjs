import assert from 'node:assert/strict';
import {webcrypto,createHash} from 'node:crypto';
import {chooseOpeningSource,verifyOpeningPair,openingOutcome,openingRect,readOpeningCache,rememberOpening,forgetOpening} from '../opening_native.js';
const source=new Uint8Array([1,2,3]),derived=new Uint8Array([4,5]);
const hash=x=>createHash('sha256').update(x).digest('hex');
const m={schema:1,scope:'OWNER_LOCAL_OPENING_ONLY',source_sha256:hash(source),derived_sha256:hash(derived),source_bytes:3,derived_bytes:2,duration_s:92};
assert.equal(chooseOpeningSource([['VIDEO/OPENING.AVI',{data:source}]]),source);
assert.equal(chooseOpeningSource([['VIDEO/OPENING.AVI',{data:source}],['video/opening.avi',{data:source}]]),null);
assert.equal((await verifyOpeningPair(source,derived,m,webcrypto.subtle)).blob.size,2);
await assert.rejects(verifyOpeningPair(source,new Uint8Array([4,6]),m,webcrypto.subtle),/OPENING_DIGEST/);
await assert.rejects(verifyOpeningPair(source,derived,{...m,duration_s:200},webcrypto.subtle),/OPENING_PAIR/);
assert.equal(openingOutcome({status:'ended'},92,92),1);
assert.equal(openingOutcome({status:'user-skip'},92,92),2);
assert.equal(openingOutcome({status:'fallback'},92,92),0);
assert.equal(openingOutcome({status:'ended'},91,92),0);
assert.deepEqual(openingRect({rect:{left:10,top:20,width:1280,height:960},width:640,height:480}),{left:10,top:260,width:1280,height:480});
assert.deepEqual(openingRect({rect:{left:0,top:0,width:960,height:720},width:1280,height:960}),{left:240,top:270,width:480,height:180});
assert.equal(openingRect({rect:{left:0,top:0,width:0,height:0},width:640,height:480}),null);
const fractional=openingRect({rect:{left:20,top:0,width:600,height:400},width:640,height:480});
assert.ok(Math.abs(fractional.width-1600/3)<1e-9 && Math.abs(fractional.height-200)<1e-9);
const metadata=new Map(),calls=[];
const cache={getMeta:async k=>metadata.get(k),setMeta:async(k,v)=>{calls.push(['put',k]);metadata.set(k,structuredClone(v));},removeMeta:async k=>{calls.push(['remove',k]);metadata.delete(k);}};
metadata.set('game',{names:['VIDEO/OPENING.AVI']});
assert.equal((await readOpeningCache(cache,source,webcrypto.subtle)).state,'MISS');
await rememberOpening(cache,source,derived,m,webcrypto.subtle);
assert.equal((await readOpeningCache(cache,source,webcrypto.subtle)).state,'VERIFIED');
assert.equal((await readOpeningCache(cache,new Uint8Array([1,2,4]),webcrypto.subtle)).state,'UNAVAILABLE_OR_INVALID');
await assert.rejects(rememberOpening(cache,source,new Uint8Array([4,6]),m,webcrypto.subtle),/OPENING_DIGEST/);
assert.equal(calls.length,1);
assert.equal((await readOpeningCache({getMeta:async()=>{throw Error('quota');}},source,webcrypto.subtle)).state,'UNAVAILABLE_OR_INVALID');
await forgetOpening(cache);
assert.deepEqual(calls,[['put','t025.opening-local-v1'],['remove','t025.opening-local-v1']]);
assert.deepEqual(metadata.get('game'),{names:['VIDEO/OPENING.AVI']});
assert.equal((await readOpeningCache(cache,source,webcrypto.subtle)).state,'MISS');
console.log('CIV2_T025_OPENING_CACHE_UNIT=PASS');
console.log('CIV2_T025_OPENING_NATIVE_UNIT=PASS');
