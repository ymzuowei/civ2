"""CIV2-T007: script-free review gates for the complete zh-Hans translation.

Does not read or require any proprietary Civilization II game media.
The font glyph coverage itself is checked by tests/lang_test.py after the
pinned Noto OFL subsets are regenerated by the trusted D-drive build.
"""
import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TRAD = ROOT / "data/native/lang/zh-Hant.txt"
SIMP = ROOT / "data/native/lang/zh-Hans.txt"


def sections(path):
    data = path.read_text(encoding="utf-8")
    result = {}
    key = None
    body = []
    for line in data.splitlines():
        if line.startswith("@@"):
            if key is not None:
                if key in result:
                    raise AssertionError(f"duplicate translation key: {key}")
                result[key] = "\n".join(body)
            key = line[2:]
            body = []
        elif key is not None:
            body.append(line)
    if key is not None:
        result[key] = "\n".join(body)
    return result


class SimplifiedChineseTranslationTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.trad = sections(TRAD)
        cls.simp = sections(SIMP)

    def test_full_keys_and_placeholders_are_preserved(self):
        self.assertGreaterEqual(len(self.trad), 3100)
        self.assertEqual(self.trad.keys(), self.simp.keys())
        for key in self.trad:
            with self.subTest(key=key):
                original = re.findall(r"%[sd]", self.trad[key])
                translated = re.findall(r"%[sd]", self.simp[key])
                self.assertEqual(original, translated)

    def test_mainland_terminology_not_character_only_transcription(self):
        self.assertEqual(self.simp["codepage"], "utf-8")
        self.assertEqual(self.simp["openciv2.language.name"], "简体中文")
        own = "\n".join(text for k, text in self.simp.items() if k.startswith("openciv2."))
        for regional in ("資料夾", "軟體", "檔案", "伺服器", "儲存空間", "匯入存檔", "匯出存檔", "存盤"):
            self.assertNotIn(regional, own)
        self.assertIn("文件夹", own)
        self.assertIn("服务器", own)
        self.assertIn("存档", own)
        self.assertEqual(self.simp["openciv2.file.save_as"], "另存为")
        self.assertEqual(self.simp["openciv2.web.export"], "导出存档")
        self.assertEqual(self.simp["openciv2.web.import"], "导入存档")

    def test_original_civ2_engineers_unit_terminology(self):
        """Civilian Engineers means 工程师/工程師, not combat sappers 工兵."""
        self.assertEqual(self.simp["rules.unit.1"], "工程师")
        self.assertEqual(self.trad["rules.unit.1"], "工程師")
        self.assertIn("工程师", self.simp["game.ENGINEERS"])
        self.assertIn("工程師", self.trad["game.ENGINEERS"])
        self.assertIn("工程师", self.simp["describe.UNIT.Engineers"])
        self.assertIn("工程師", self.trad["describe.UNIT.Engineers"])
        self.assertIn("工程师", self.simp["game.ONLYSETTLERS"])
        self.assertIn("工程師", self.trad["game.ONLYSETTLERS"])
        for lang, sections_map in (("zh-Hans", self.simp), ("zh-Hant", self.trad)):
            with self.subTest(lang=lang):
                # This older term referred to the same non-combat worker
                # unit in game rules, Civilopedia, advisors and instructions.
                remaining = [key for key, text in sections_map.items() if "工兵" in text]
                self.assertEqual(remaining, [])
                self.assertEqual(sections_map["rules.advance.10"], "化学" if lang == "zh-Hans" else "化學")
                self.assertEqual(sections_map["rules.advance.28"], "炸药" if lang == "zh-Hans" else "炸藥")

    def test_both_chinese_versions_are_separate(self):
        self.assertEqual(self.trad["openciv2.language.name"], "繁體中文")
        self.assertNotEqual(self.trad["openciv2.web.intro"], self.simp["openciv2.web.intro"])

    def test_natural_web_copy_maintains_markup(self):
        intro = self.simp["openciv2.web.intro"]
        self.assertIn("<em>", intro)
        self.assertIn("<code>", intro)
        self.assertIn("光盘镜像", intro)
        self.assertIn("浏览器", intro)
        self.assertIn("文件", intro)


if __name__ == "__main__":
    unittest.main()
